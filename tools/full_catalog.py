def build_catalog():
    """返回 {品类: [(名称, kcal, 蛋白, 脂肪, 碳水, 钠, 钙, 价格, 是否实测), ...]}"""
    name2cat = {}
    for cat, names in CATEGORIES:
        for n in names:
            name2cat[n] = cat

    catalog = {}
    covered = set()
    for cat, names in CATEGORIES:
        items = []
        for n in names:
            if n not in NUTRITION:
                continue
            kcal, p, f, c, na, ca = NUTRITION[n]
            price = MEASURED_PRICE.get(n) or REF_PRICE.get(n) or 0.0
            if price == 0.0 and n in ALIASES:
                price = REF_PRICE.get(ALIASES[n], 0.0)
            measured = n in MEASURED_PRICE
            items.append({
                "name": n, "energyKcal": kcal, "protein": p, "fat": f,
                "carbohydrate": c, "sodium": na, "calcium": ca,
                "price": round(price, 2), "measured": measured,
            })
            covered.add(n)
        if items:
            catalog[cat] = items

    missing = set(NUTRITION) - covered
    return catalog, missing


